# Generates src/Headliner/Data/WorldMap.lua from Natural Earth country borders (world-atlas 2.0.2, countries-50m, public domain).
# Equirectangular grid, 1 degree per cell, latitude 80N..58S. Playable countries get their own cells (for hover highlighting).
import json, sys
from shapely.geometry import shape, Point, Polygon, MultiPolygon
from shapely.prepared import prep
topo = json.load(open(sys.argv[1]))
sx, sy = topo["transform"]["scale"]; tx, ty = topo["transform"]["translate"]
arcs = []
for arc in topo["arcs"]:
    x = y = 0; pts = []
    for dx, dy in arc:
        x += dx; y += dy; pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)
def ring(idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts
def geom(g):
    if g["type"] == "Polygon":
        return Polygon(ring(g["arcs"][0]), [ring(r) for r in g["arcs"][1:]])
    if g["type"] == "MultiPolygon":
        parts = []
        for p in g["arcs"]:
            q = Polygon(ring(p[0]), [ring(r) for r in p[1:]]).buffer(0)
            parts.extend(q.geoms if q.geom_type == "MultiPolygon" else [q])
        return MultiPolygon([q for q in parts if not q.is_empty])
    return None
IDS = {"826": "uk", "372": "ie", "250": "fr", "528": "nl", "276": "de", "756": "ch", "380": "it", "724": "es", "752": "se",
       "840": "us", "124": "ca", "484": "mx", "076": "br", "032": "ar", "392": "jp", "410": "kr", "036": "au", "784": "ae", "710": "za", "056": "be", "040": "at", "616": "pl", "578": "no", "208": "dk", "620": "pt", "203": "cz", "152": "cl", "170": "co", "356": "in", "608": "ph", "702": "sg", "764": "th", "554": "nz"}
W, H, TOP, BOT = 360, 138, 80.0, -58.0
countries, others = {}, []
for g in topo["objects"]["countries"]["geometries"]:
    gm = geom(g)
    if gm is None: continue
    if gm.geom_type == "Polygon": gm = gm.buffer(0)
    cid = IDS.get(str(g.get("id", "")).zfill(3))
    if cid and (cid not in countries or gm.area > countries[cid].area): countries[cid] = gm
    elif cid: others.append(prep(gm))
    else: others.append(prep(gm))
prepC = {k: prep(v) for k, v in countries.items()}
allLand = others + list(prepC.values())
def raster(w, h, test):
    grid = [[None] * w for _ in range(h)]
    for j in range(h):
        lat = TOP - (j + 0.5) * (TOP - BOT) / h
        for i in range(w):
            lon = -180 + (i + 0.5) * 360 / w
            cs = 360 / w
            for dy, dx in ((0, 0), (0.3, 0.3), (-0.3, -0.3), (0.3, -0.3), (-0.3, 0.3)):
                v = test(Point(lon + dx * cs, lat + dy * cs))
                if v: grid[j][i] = v; break
    return grid
def runs(grid, pred):
    out = []
    for j, row in enumerate(grid):
        i = 0
        while i < len(row):
            if pred(row[i]):
                s0 = i
                while i < len(row) and pred(row[i]): i += 1
                out.append((j, s0, i - s0))
            else: i += 1
    return out
# 1 degree: all land (drawn underneath)
g1 = raster(W, H, lambda p: "land" if any(o.contains(p) for o in allLand) else None)
land = runs(g1, lambda v: v == "land")
# 0.5 degree: playable countries (drawn on top, clickable)
W2, H2 = W * 2, H * 2
def ctest(p):
    for cid, pg in prepC.items():
        if pg.contains(p): return cid
    return None
g2 = raster(W2, H2, ctest)
for cid, gm in countries.items():
    if not any(v == cid for row in g2 for v in row):
        c = gm.representative_point(); g2[int((TOP - c.y) / (TOP - BOT) * H2)][int((c.x + 180) / 360 * W2)] = cid
def rects(runlist):
    # merge identical runs of consecutive rows into rectangles: (row, col, w, h)
    open_, out = {}, []
    byrow = {}
    for j, c, l in runlist:
        byrow.setdefault(j, []).append((c, l))
    for j in sorted(byrow):
        nxt = {}
        for c, l in byrow[j]:
            if (c, l) in open_ and open_[(c, l)][0] + open_[(c, l)][3] == j:
                r = open_.pop((c, l)); r[3] += 1; nxt[(c, l)] = r
            else:
                nxt[(c, l)] = [j, c, l, 1]
        out.extend(open_.values()); open_ = nxt
    out.extend(open_.values())
    return out
landR = rects(land)
lines = ["-- AUTO-GENERATED by tools/gen_worldmap.py from Natural Earth borders (world-atlas 2.0.2, public domain).",
         "-- land: 1 degree grid (W x H). countries: 0.5 degree grid (CW x CH). Latitude 80N..58S.",
         "-- rects = { row, col, width, height } in grid cells (0-based).",
         "return {", f"\tW = {W},", f"\tH = {H},", f"\tCW = {W2},", f"\tCH = {H2},", f"\tLAT_TOP = {TOP},", f"\tLAT_BOTTOM = {BOT},",
         "\tland = { " + ", ".join("{%d,%d,%d,%d}" % tuple(r) for r in landR) + " },", "\tcountries = {"]
total = len(landR)
for cid in sorted(countries):
    rr = rects(runs(g2, lambda v, c=cid: v == c)); total += len(rr)
    gm = countries[cid]
    main = max(gm.geoms, key=lambda p: p.area) if gm.geom_type == "MultiPolygon" else gm
    c = main.representative_point() if cid in ("us", "ca") else main.centroid
    lines.append(f"\t\t[\"{cid}\"] = {{ lat = {c.y:.2f}, lon = {c.x:.2f}, rects = {{ " + ", ".join("{%d,%d,%d,%d}" % tuple(r) for r in rr) + " } },")
lines += ["\t},", "}", ""]
open("src/Headliner/Data/WorldMap.lua", "w").write("\n".join(lines))
print("parts:", total, "land rects:", len(landR))
